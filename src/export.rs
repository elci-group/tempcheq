fn md_escape_cell(s: &str) -> String {
    s.replace('|', "\\|")
}

fn ascii_bar(count: usize, max: usize, width: usize) -> String {
    if max == 0 {
        return "░".repeat(width);
    }
    let filled = ((count as f64 / max as f64) * width as f64).round() as usize;
    let filled = filled.min(width);
    format!("{}{}", "█".repeat(filled), "░".repeat(width - filled))
}

pub fn render_markdown(root: &Path, entries: &[Entry], title: Option<&str>) -> String {
    let mut out = String::new();
    let s = summarize(entries);
    let (flagged, rest) = split_and_sort(entries);

    out.push_str(&format!("# {}\n\n", title_for(root, title)));
    out.push_str(&format!("Workspace: `{}`\n\n", root.display()));
    out.push_str(&format!("Generated by TempCheq v{}\n\n", env!("CARGO_PKG_VERSION")));

    out.push_str("## Summary\n\n");
    out.push_str("| Metric | Count |\n|---|---:|\n");
    out.push_str(&format!("| Inference actions found | {} |\n", s.total));
    out.push_str(&format!("| Temperature-controlled | {} |\n", s.controlled));
    out.push_str(&format!("| Implicit / default | {} |\n", s.implicit));
    out.push_str(&format!("| Temperature-inapplicable | {} |\n", s.inapplicable));
    out.push_str(&format!("| Flagged for review | {} |\n", s.flagged));
    out.push('\n');

    let breakdown_max = s.controlled.max(s.implicit).max(s.inapplicable).max(1);
    out.push_str("```\n");
    out.push_str(&format!(
        "controlled    {} {}\n",
        ascii_bar(s.controlled, breakdown_max, 30),
        s.controlled
    ));
    out.push_str(&format!(
        "implicit      {} {}\n",
        ascii_bar(s.implicit, breakdown_max, 30),
        s.implicit
    ));
    out.push_str(&format!(
        "inapplicable  {} {}\n",
        ascii_bar(s.inapplicable, breakdown_max, 30),
        s.inapplicable
    ));
    out.push_str("```\n\n");

    out.push_str("## Task classification\n\n```\n");
    let ccounts = class_counts(entries);
    let class_max = ccounts.iter().map(|(_, n)| *n).max().unwrap_or(0).max(1);
    for (class, n) in &ccounts {
        out.push_str(&format!(
            "{:<26}{} {}\n",
            class.label(),
            ascii_bar(*n, class_max, 24),
            n
        ));
    }
    out.push_str("```\n\n");

    out.push_str("## Flagged for review\n\n");
    if flagged.is_empty() {
        out.push_str("No actions materially outside their estimated optimum.\n\n");
    } else {
        out.push_str(
            "| Action | Location | Class | Current | Optimal | Deviation | Confidence |\n\
             |---|---|---|---:|---:|---:|---:|\n",
        );
        for e in &flagged {
            let verdict = e
                .rec
                .verdict(&e.action)
                .map(|v| format!("{v:+.2}"))
                .unwrap_or_else(|| "—".to_string());
            out.push_str(&format!(
                "| `{}` | {}:{} | {} | {} | {:.2} | {} | {:.2} |\n",
                md_escape_cell(&e.action.name),
                md_escape_cell(&e.action.file.display().to_string()),
                e.action.line,
                e.rec.class.label(),
                e.action.temperature.as_display(),
                e.rec.ideal,
                verdict,
                e.rec.confidence,
            ));
        }
        out.push('\n');
        out.push_str("### Reasoning\n\n");
        for e in &flagged {
            out.push_str(&format!(
                "**`{}`** ({}:{})\n\n",
                md_escape_cell(&e.action.name),
                e.action.file.display(),
                e.action.line
            ));
            for r in &e.rec.reasons {
                out.push_str(&format!("- {r}\n"));
            }
            out.push('\n');
        }
    }

    out.push_str("## All other actions\n\n");
    if rest.is_empty() {
        out.push_str("(none)\n\n");
    } else {
        out.push_str("| Action | Location | Kind | State | Class | Value |\n|---|---|---|---|---|---:|\n");
        for e in &rest {
            out.push_str(&format!(
                "| `{}` | {}:{} | {} | {} | {} | {} |\n",
                md_escape_cell(&e.action.name),
                md_escape_cell(&e.action.file.display().to_string()),
                e.action.line,
                e.action.source_kind.label(),
                temperature_state_label(&e.action.temperature),
                e.rec.class.label(),
                e.action.temperature.as_display(),
            ));
        }
        out.push('\n');
    }

    out.push_str("## Methodology\n\n");
    out.push_str(
        "'Optimal' values are heuristic priors from keyword-based task classification, not \
         measured outcomes — treat them as a starting point for review, not a verdict. Run \
         `tempcheq --benchmark` for a (simulated, clearly labeled) perturbation curve, or wire \
         in a real evaluation to ground these numbers empirically. Findings from broad markers \
         (e.g. any file containing a `\"model\":` key) are more prone to false positives than \
         explicit temperature assignments — cross-check low-confidence rows before acting.\n",
    );

    out
}

fn temperature_state_label(t: &TemperatureState) -> &'static str {
    match t {
        TemperatureState::Explicit(_) => "explicit",
        TemperatureState::Implicit => "implicit",
        TemperatureState::Inapplicable => "inapplicable",
    }
}

