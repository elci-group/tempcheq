fn esc_html(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// A minimal, self-contained horizontal bar chart. No JS, no external
/// fonts/CDN — every value baked into plain SVG shapes and `<text>`.
fn svg_bar_chart(rows: &[(String, usize)], color: &str) -> String {
    let max = rows.iter().map(|(_, n)| *n).max().unwrap_or(0).max(1);
    let row_h = 26;
    let label_w = 190;
    let bar_max_w = 260;
    let width = label_w + bar_max_w + 60;
    let height = row_h * rows.len() + 10;

    let mut svg = format!(
        "<svg viewBox=\"0 0 {width} {height}\" width=\"100%\" height=\"{height}\" \
         xmlns=\"http://www.w3.org/2000/svg\" role=\"img\" aria-label=\"bar chart\">"
    );
    for (i, (label, count)) in rows.iter().enumerate() {
        let y = i * row_h;
        let bar_w = ((*count as f64 / max as f64) * bar_max_w as f64).round() as i64;
        let bar_w = bar_w.max(if *count > 0 { 2 } else { 0 });
        svg.push_str(&format!(
            "<text x=\"0\" y=\"{ty}\" font-size=\"12\" fill=\"#334155\">{label}</text>\
             <rect x=\"{label_w}\" y=\"{ry}\" width=\"{bar_w}\" height=\"14\" rx=\"2\" fill=\"{color}\"/>\
             <text x=\"{tx}\" y=\"{ty}\" font-size=\"12\" fill=\"#334155\">{count}</text>",
            ty = y + 12,
            ry = y + 2,
            tx = label_w + bar_w as usize + 8,
            label = esc_html(label),
        ));
    }
    svg.push_str("</svg>");
    svg
}

fn verdict_badge(verdict: Option<f32>) -> String {
    match verdict {
        None => "<span class=\"badge badge-neutral\">—</span>".to_string(),
        Some(v) => {
            let cls = if v.abs() > 0.3 {
                "badge-high"
            } else {
                "badge-med"
            };
            format!("<span class=\"badge {cls}\">{v:+.2}</span>")
        }
    }
}

pub fn render_html(root: &Path, entries: &[Entry], title: Option<&str>) -> String {
    let s = summarize(entries);
    let (flagged, rest) = split_and_sort(entries);
    let ccounts = class_counts(entries);
    let title_str = title_for(root, title);

    let breakdown_svg = svg_bar_chart(
        &[
            ("Temperature-controlled".to_string(), s.controlled),
            ("Implicit / default".to_string(), s.implicit),
            ("Inapplicable".to_string(), s.inapplicable),
        ],
        "#2563eb",
    );
    let class_svg = svg_bar_chart(
        &ccounts
            .iter()
            .map(|(c, n)| (c.label().to_string(), *n))
            .collect::<Vec<_>>(),
        "#7c3aed",
    );

    let mut flagged_rows = String::new();
    if flagged.is_empty() {
        flagged_rows
            .push_str("<tr><td colspan=\"7\" class=\"empty\">No actions materially outside their estimated optimum.</td></tr>");
    } else {
        for e in &flagged {
            flagged_rows.push_str(&format!(
                "<tr><td><code>{}</code></td><td>{}:{}</td><td>{}</td><td>{}</td>\
                 <td>{:.2}</td><td>{}</td><td>{:.2}</td></tr>",
                esc_html(&e.action.name),
                esc_html(&e.action.file.display().to_string()),
                e.action.line,
                esc_html(e.rec.class.label()),
                esc_html(&e.action.temperature.as_display()),
                e.rec.ideal,
                verdict_badge(e.rec.verdict(&e.action)),
                e.rec.confidence,
            ));
        }
    }

    let mut reasoning = String::new();
    for e in &flagged {
        reasoning.push_str(&format!(
            "<div class=\"reason-card\"><h3><code>{}</code> <span class=\"loc\">{}:{}</span></h3><ul>",
            esc_html(&e.action.name),
            esc_html(&e.action.file.display().to_string()),
            e.action.line
        ));
        for r in &e.rec.reasons {
            reasoning.push_str(&format!("<li>{}</li>", esc_html(r)));
        }
        reasoning.push_str("</ul></div>");
    }

    let mut rest_rows = String::new();
    if rest.is_empty() {
        rest_rows.push_str("<tr><td colspan=\"6\" class=\"empty\">(none)</td></tr>");
    } else {
        for e in &rest {
            rest_rows.push_str(&format!(
                "<tr><td><code>{}</code></td><td>{}:{}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td></tr>",
                esc_html(&e.action.name),
                esc_html(&e.action.file.display().to_string()),
                e.action.line,
                esc_html(e.action.source_kind.label()),
                esc_html(temperature_state_label(&e.action.temperature)),
                esc_html(e.rec.class.label()),
                esc_html(&e.action.temperature.as_display()),
            ));
        }
    }

    format!(
        r#"<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title_esc}</title>
<style>
{css}
</style>
</head>
<body>
<div class="container">
<header>
<h1>{title_esc}</h1>
<p class="workspace">Workspace: <code>{workspace}</code></p>
<p class="version">Generated by TempCheq v{version}</p>
</header>

<section class="summary-grid">
<div class="stat"><div class="stat-value">{total}</div><div class="stat-label">Actions found</div></div>
<div class="stat"><div class="stat-value">{controlled}</div><div class="stat-label">Temperature-controlled</div></div>
<div class="stat"><div class="stat-value">{implicit}</div><div class="stat-label">Implicit / default</div></div>
<div class="stat"><div class="stat-value">{inapplicable}</div><div class="stat-label">Inapplicable</div></div>
<div class="stat stat-flag"><div class="stat-value">{flagged_n}</div><div class="stat-label">Flagged for review</div></div>
</section>

<section>
<h2>Breakdown</h2>
<div class="chart">{breakdown_svg}</div>
</section>

<section>
<h2>Task classification</h2>
<div class="chart">{class_svg}</div>
</section>

<section>
<h2>Flagged for review</h2>
<div class="table-wrap">
<table>
<thead><tr><th>Action</th><th>Location</th><th>Class</th><th>Current</th><th>Optimal</th><th>Deviation</th><th>Confidence</th></tr></thead>
<tbody>{flagged_rows}</tbody>
</table>
</div>
{reasoning}
</section>

<section>
<h2>All other actions</h2>
<div class="table-wrap">
<table>
<thead><tr><th>Action</th><th>Location</th><th>Kind</th><th>State</th><th>Class</th><th>Value</th></tr></thead>
<tbody>{rest_rows}</tbody>
</table>
</div>
</section>

<section class="methodology">
<h2>Methodology</h2>
<p>"Optimal" values are heuristic priors from keyword-based task classification, not measured
outcomes — treat them as a starting point for review, not a verdict. Run
<code>tempcheq --benchmark</code> for a (simulated, clearly labeled) perturbation curve, or wire
in a real evaluation to ground these numbers empirically. Findings from broad markers (e.g. any
file containing a <code>"model":</code> key) are more prone to false positives than explicit
temperature assignments — cross-check low-confidence rows before acting.</p>
</section>

</div>
</body>
</html>
"#,
        title_esc = esc_html(&title_str),
        css = REPORT_CSS,
        workspace = esc_html(&root.display().to_string()),
        version = env!("CARGO_PKG_VERSION"),
        total = s.total,
        controlled = s.controlled,
        implicit = s.implicit,
        inapplicable = s.inapplicable,
        flagged_n = s.flagged,
        breakdown_svg = breakdown_svg,
        class_svg = class_svg,
        flagged_rows = flagged_rows,
        reasoning = reasoning,
        rest_rows = rest_rows,
    )
}

