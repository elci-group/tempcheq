//! Deterministic Markdown/HTML report rendering for `tempcheq report`.
//!
//! "Deterministic" means: given the same discovered actions, the output
//! bytes are identical on every run. In practice that means no wall-clock
//! timestamps, no HashMap iteration (Rust randomizes its hash seed per
//! process), and explicit sort keys everywhere findings are grouped or
//! listed — so two reports generated from the same commit, possibly on
//! different machines, diff as empty.

use crate::action::TemperatureState;
use crate::classify::{TaskClass, ALL_CLASSES};
use crate::report::Entry;
use std::cmp::Ordering;
use std::path::Path;

pub struct Summary {
    pub total: usize,
    pub controlled: usize,
    pub implicit: usize,
    pub inapplicable: usize,
    pub flagged: usize,
}

pub fn summarize(entries: &[Entry]) -> Summary {
    Summary {
        total: entries.len(),
        controlled: entries
            .iter()
            .filter(|e| matches!(e.action.temperature, TemperatureState::Explicit(_)))
            .count(),
        implicit: entries
            .iter()
            .filter(|e| matches!(e.action.temperature, TemperatureState::Implicit))
            .count(),
        inapplicable: entries
            .iter()
            .filter(|e| matches!(e.action.temperature, TemperatureState::Inapplicable))
            .count(),
        flagged: entries
            .iter()
            .filter(|e| e.rec.is_material_deviation(&e.action))
            .count(),
    }
}

/// Count per `TaskClass`, in `ALL_CLASSES` order (fixed, not hash order)
/// so chart row order never depends on discovery or process hash seed.
fn class_counts(entries: &[Entry]) -> Vec<(TaskClass, usize)> {
    ALL_CLASSES
        .iter()
        .map(|c| (*c, entries.iter().filter(|e| e.rec.class == *c).count()))
        .collect()
}

/// Flagged entries first (most severe deviation first), then everything
/// else in file/line order. Both groups break ties on (file, line) so the
/// ordering is fully determined by the findings themselves.
fn split_and_sort(entries: &[Entry]) -> (Vec<&Entry>, Vec<&Entry>) {
    let mut flagged: Vec<&Entry> = Vec::new();
    let mut rest: Vec<&Entry> = Vec::new();
    for e in entries {
        if e.rec.is_material_deviation(&e.action) {
            flagged.push(e);
        } else {
            rest.push(e);
        }
    }
    let file_line = |e: &&Entry| (e.action.file.clone(), e.action.line);
    flagged.sort_by(|a, b| {
        let da = a.rec.verdict(&a.action).map(|v| v.abs()).unwrap_or(0.0);
        let db = b.rec.verdict(&b.action).map(|v| v.abs()).unwrap_or(0.0);
        db.partial_cmp(&da)
            .unwrap_or(Ordering::Equal)
            .then_with(|| file_line(a).cmp(&file_line(b)))
    });
    rest.sort_by_key(file_line);
    (flagged, rest)
}

fn title_for(root: &Path, title: Option<&str>) -> String {
    title
        .map(|t| t.to_string())
        .unwrap_or_else(|| format!("TempCheq Report — {}", root.display()))
}

